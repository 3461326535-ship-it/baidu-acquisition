import { chmod, mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";
import type { Credentials } from "./types.ts";

function parseEnvFile(content: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const index = line.indexOf("=");
    if (index < 1) continue;
    const key = line.slice(0, index).trim();
    let value = line.slice(index + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    result[key] = value;
  }
  return result;
}

function quoteEnv(value: string): string {
  return JSON.stringify(value);
}

function expiryFrom(source: Record<string, unknown>, prefix = ""): string | undefined {
  const explicit = source[`${prefix}ExpiresTime`] || source[`${prefix}expires_time`];
  if (explicit) {
    const parsed = Date.parse(String(explicit));
    if (Number.isFinite(parsed)) return new Date(parsed).toISOString();
  }
  const seconds = Number(
    source[`${prefix}ExpiresIn`] || source[`${prefix}expires_in`] ||
    (!prefix ? source.expireIn || source.expires : undefined),
  );
  return Number.isFinite(seconds) && seconds > 0
    ? new Date(Date.now() + seconds * 1000).toISOString()
    : undefined;
}

async function writeTokenStore(path: string, values: Record<string, string>): Promise<void> {
  const { dirname, basename, join } = await import("node:path");
  const directory = dirname(path);
  await mkdir(directory, { recursive: true });
  const tempPath = join(directory, `.${basename(path)}.${process.pid}.tmp`);
  const order = [
    "BAIDU_ACCESS_TOKEN", "BAIDU_REFRESH_TOKEN", "BAIDU_TOKEN_EXPIRES_AT",
    "BAIDU_REFRESH_TOKEN_EXPIRES_AT", "BAIDU_AUTH_USER_ID", "BAIDU_OPEN_ID",
    "BAIDU_TOKEN_UPDATED_AT",
  ];
  const keys = [...order, ...Object.keys(values).filter(key => !order.includes(key)).sort()]
    .filter((key, index, all) => all.indexOf(key) === index && values[key]);
  const content = [
    "# Generated by baidu-acquisition. Do not commit this file.",
    ...keys.map(key => `${key}=${quoteEnv(values[key]!)}`),
    "",
  ].join("\n");
  await writeFile(tempPath, content, { encoding: "utf8", mode: 0o600 });
  await rename(tempPath, path);
  try { await chmod(path, 0o600); } catch { /* Best effort on Windows. */ }
}

async function refreshCredentials(
  current: Record<string, string>,
  tokenStorePath: string,
): Promise<Record<string, string>> {
  const appId = process.env.BAIDU_APP_ID;
  const secretKey = process.env.BAIDU_SECRET_KEY;
  const refreshToken = process.env.BAIDU_REFRESH_TOKEN || current.BAIDU_REFRESH_TOKEN;
  const userId = current.BAIDU_AUTH_USER_ID || process.env.BAIDU_USER_ID;
  if (!appId || !secretKey || !refreshToken || !userId) {
    throw new Error("Access token expired; refresh requires BAIDU_APP_ID, BAIDU_SECRET_KEY, refresh token, and auth user ID.");
  }

  const url = process.env.BAIDU_OAUTH_REFRESH_TOKEN_URL || "https://u.baidu.com/oauth/refreshToken";
  const response = await fetch(url, {
    method: "POST",
    headers: { "content-type": "application/json;charset:utf-8;" },
    body: JSON.stringify({ appId, secretKey, userId: Number(userId), refreshToken }),
  });
  const payload = await response.json() as Record<string, unknown>;
  if (!response.ok || (payload.code !== undefined && payload.code !== 0)) {
    throw new Error(`OAuth refresh failed with HTTP ${response.status}.`);
  }
  const source = payload.data && typeof payload.data === "object"
    ? payload.data as Record<string, unknown>
    : payload;
  const accessToken = String(source.accessToken || source.access_token || "");
  if (!accessToken) throw new Error("OAuth refresh response did not include an access token.");
  const next: Record<string, string> = {
    ...current,
    BAIDU_ACCESS_TOKEN: accessToken,
    BAIDU_REFRESH_TOKEN: String(source.refreshToken || source.refresh_token || refreshToken),
    BAIDU_AUTH_USER_ID: String(source.userId || userId),
    BAIDU_TOKEN_UPDATED_AT: new Date().toISOString(),
  };
  const expiresAt = expiryFrom(source);
  const refreshExpiresAt = expiryFrom(source, "refresh");
  if (expiresAt) next.BAIDU_TOKEN_EXPIRES_AT = expiresAt;
  if (refreshExpiresAt) next.BAIDU_REFRESH_TOKEN_EXPIRES_AT = refreshExpiresAt;
  if (source.openId) next.BAIDU_OPEN_ID = String(source.openId);
  await writeTokenStore(tokenStorePath, next);
  return next;
}

export async function loadCredentials(): Promise<Credentials> {
  const tokenStorePath = process.env.BAIDU_TOKEN_STORE ||
    join(homedir(), ".baidu-acquisition", ".baidu-auth.env");
  let stored: Record<string, string> = {};
  try {
    stored = parseEnvFile(await readFile(tokenStorePath, "utf8"));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }

  const configuredExpiry = process.env.BAIDU_TOKEN_EXPIRES_AT || stored.BAIDU_TOKEN_EXPIRES_AT;
  const shouldRefresh = configuredExpiry
    ? Date.parse(configuredExpiry) - Date.now() <= 5 * 60 * 1000
    : false;
  if (shouldRefresh) stored = await refreshCredentials(stored, tokenStorePath);
  const accessToken = process.env.BAIDU_ACCESS_TOKEN || stored.BAIDU_ACCESS_TOKEN;
  if (!accessToken) {
    throw new Error(`Missing access token. Set BAIDU_TOKEN_STORE or BAIDU_ACCESS_TOKEN.`);
  }

  const appId = process.env.BAIDU_APP_ID;
  const secretKey = process.env.BAIDU_SECRET_KEY;
  const refreshToken = process.env.BAIDU_REFRESH_TOKEN || stored.BAIDU_REFRESH_TOKEN;
  const authUserId = stored.BAIDU_AUTH_USER_ID;
  const expiresAt = stored.BAIDU_TOKEN_EXPIRES_AT;
  const refreshExpiresAt = stored.BAIDU_REFRESH_TOKEN_EXPIRES_AT;
  return {
    accessToken,
    tokenStorePath,
    ...(appId ? { appId } : {}),
    ...(secretKey ? { secretKey } : {}),
    ...(refreshToken ? { refreshToken } : {}),
    ...(authUserId ? { authUserId } : {}),
    ...(expiresAt ? { expiresAt } : {}),
    ...(refreshExpiresAt ? { refreshExpiresAt } : {}),
  };
}

